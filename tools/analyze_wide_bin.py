#!/usr/bin/env python3
"""
Wide-offset comparison (90-180 deg bin) per sample and dataset, paired on the same frames: the initialisation-free
estimate (which does not read T0, so one pose per frame) against every refiner started from the T0 of that bin;
exact McNemar test on the discordant frames. Supports the scope of the claim in Section 4 (pooled vs per subset).

  python tools/analyze_wide_bin.py
Writes manuscript/computational_visual_media/wide_bin_macros.tex and benchmark_results/wide_bin_summary.json.
"""
from __future__ import annotations

import importlib.util
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("rep", Path(__file__).resolve().parent / "analyze_replication.py")
rep = importlib.util.module_from_spec(spec)
spec.loader.exec_module(rep)
eb = rep.eb
KEY = {"lmo": "LMO", "lm": "LM", "tless": "TLESS"}
EST = (("ours_full", "Ours"), ("ours_ms", "OursMs"), ("ours_msf", "OursMsf"))
NAME = {"wapr_refine": "WAPR's refiner", "fp_refine": "FoundationPose's refiner", "mp_refine": "MegaPose's refiner",
        "gt_refine": "GoTrack", "scflow2": "SCFlow2", "diffdope": "Diff-DOPE", "sdfr": "SDFR"}
MK = {"wapr_refine": "Wapr", "fp_refine": "Fp", "mp_refine": "Mp", "gt_refine": "Gt", "scflow2": "Scflow", "diffdope": "Dd", "sdfr": "Sdfr"}


def fmt_p(p: float) -> str:
    """'=0.07' or '<10^{-11}', to follow a $p$ in the text."""
    if p >= 0.001:
        return f"={p:.2f}" if p >= 0.01 else f"={p:.3f}"
    return f"<10^{{-{int(math.floor(-math.log10(p)))}}}" if p > 0 else "<10^{-16}"


def main() -> int:
    data = {s: {ds: rep.load(root, ds) for ds, _ in eb.DATASETS} for s, root in (("A", rep.A), ("B", rep.B))}
    refs = [k for k, _, _ in rep.REFINERS if any(data[s][ds].get(k) for s in data for ds in data[s])]
    groups = {}
    for s in ("A", "B"):
        for ds, _ in eb.DATASETS:
            groups[(s, ds)] = data[s][ds]
    subsets = {f"{s}{KEY[ds]}": [(s, ds)] for s in ("A", "B") for ds, _ in eb.DATASETS}
    subsets.update({"A": [("A", ds) for ds, _ in eb.DATASETS], "B": [("B", ds) for ds, _ in eb.DATASETS],
                    "AB": [(s, ds) for s in ("A", "B") for ds, _ in eb.DATASETS]})
    for ds, _ in eb.DATASETS:
        subsets[f"AB{KEY[ds]}"] = [("A", ds), ("B", ds)]
    summary, macros = {}, ["% Auto-generated by tools/analyze_wide_bin.py"]
    for name, members in subsets.items():
        row = {}
        for est_key, est_mk in EST:
            est = {r["tag"]: rep.ok(r) for g in members for r in groups[g].get(est_key, [])}
            row[est_key] = {"n": len(est), "sr": 100.0 * sum(est.values()) / max(1, len(est))}
            for ref in refs:
                rr = {r["tag"]: rep.ok(r) for g in members for r in groups[g].get(ref, []) if str(r.get("bin")) == "90-180"}
                tags = sorted(set(est) & set(rr))
                if not tags:
                    continue
                b = sum(est[t] and not rr[t] for t in tags)
                c = sum(rr[t] and not est[t] for t in tags)
                row[est_key][ref] = {"n": len(tags), "sr_est": 100.0 * sum(est[t] for t in tags) / len(tags),
                                     "sr_ref": 100.0 * sum(rr[t] for t in tags) / len(tags), "b": b, "c": c, "p": rep.mcnemar(b, c)}
        summary[name] = row
    print(f"{'subset':8s} {'n':>4s} {'ours':>5s} {'ms':>5s} | " + " | ".join(f"{r:>14s}" for r in refs))
    for name, row in summary.items():
        o, m = row["ours_full"], row["ours_ms"]
        cells = []
        for ref in refs:
            x = o.get(ref)
            cells.append(f"{x['sr_ref']:5.0f} p={x['p']:.2g}" if x else f"{'--':>14s}")
        print(f"{name:8s} {o['n']:4d} {o['sr']:5.0f} {m['sr']:5.0f} | " + " | ".join(f"{c:>14s}" for c in cells))
    best = {name: max((r for r in refs if r in row["ours_full"]), key=lambda r: row["ours_full"][r]["sr_ref"]) for name, row in summary.items()}
    for name, row in summary.items():
        o, m = row["ours_full"], row["ours_ms"]
        bref = best[name]
        pre = "AB" if name.startswith("AB") else name[0]
        mk = {"A": "First", "B": "Second", "AB": "Pool"}[pre] + name[len(pre):]
        macros += [f"\\providecommand{{\\Wide{mk}N}}{{{o['n']}}}", f"\\providecommand{{\\Wide{mk}Ours}}{{{o['sr']:.0f}}}",
                   f"\\providecommand{{\\Wide{mk}OursMs}}{{{m['sr']:.0f}}}", f"\\providecommand{{\\Wide{mk}Best}}{{{o[bref]['sr_ref']:.0f}}}",
                   f"\\providecommand{{\\Wide{mk}BestP}}{{{fmt_p(o[bref]['p'])}}}", f"\\providecommand{{\\Wide{mk}MsBestP}}{{{fmt_p(m[bref]['p'])}}}"]
        for est_key, est_mk in EST:
            e_ = row.get(est_key, {})
            for r in refs:
                if r in e_:
                    pre_ = "" if est_key == "ours_full" else est_mk
                    macros += [f"\\providecommand{{\\Wide{mk}{pre_}{MK[r]}SR}}{{{e_[r]['sr_ref']:.0f}}}",
                               f"\\providecommand{{\\Wide{mk}{pre_}{MK[r]}P}}{{{fmt_p(e_[r]['p'])}}}"]
        rest = [r for r in refs if r not in ("wapr_refine", "gt_refine") and r in o]
        if rest:
            macros += [f"\\providecommand{{\\Wide{mk}RestMinSR}}{{{min(o[r]['sr_ref'] for r in rest):.0f}}}",
                       f"\\providecommand{{\\Wide{mk}RestMaxSR}}{{{max(o[r]['sr_ref'] for r in rest):.0f}}}",
                       f"\\providecommand{{\\Wide{mk}RestMaxP}}{{{fmt_p(max(o[r]['p'] for r in rest))}}}"]
        others = [r for r in refs if r != bref and r in o]
        if others:
            macros += [f"\\providecommand{{\\Wide{mk}BestName}}{{{NAME.get(bref, bref)}}}",
                       f"\\providecommand{{\\Wide{mk}OthersMaxSR}}{{{max(o[r]['sr_ref'] for r in others):.0f}}}",
                       f"\\providecommand{{\\Wide{mk}OthersMaxP}}{{{fmt_p(max(o[r]['p'] for r in others))}}}",
                       f"\\providecommand{{\\Wide{mk}SecondName}}{{{NAME.get(max(others, key=lambda r: o[r]['sr_ref']), '')}}}",
                       f"\\providecommand{{\\Wide{mk}SecondSR}}{{{max(o[r]['sr_ref'] for r in others):.0f}}}"]
        f_ = row.get("ours_msf", {})
        if f_.get("n") and bref in f_:
            macros += [f"\\providecommand{{\\Wide{mk}OursMsf}}{{{f_['sr']:.0f}}}", f"\\providecommand{{\\Wide{mk}MsfBestP}}{{{fmt_p(f_[bref]['p'])}}}"]
        summary[name]["best_refiner"] = bref
    (ROOT / "manuscript" / "computational_visual_media" / "wide_bin_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    (ROOT / "benchmark_results" / "wide_bin_summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    print("best refiner per subset:", best)
    print("[written] wide_bin_macros.tex, benchmark_results/wide_bin_summary.json")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
