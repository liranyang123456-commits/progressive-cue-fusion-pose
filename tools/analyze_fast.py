#!/usr/bin/env python3
"""
The proposed method at an eighth of the proposal and beam budgets (bop_full6dof_eval.py --budget 1/8) on the BOP frames
of Table 4, against the full budget on the same frames (symmetry-aware SR@10 deg, paired exact McNemar test).
The 1/8 runs were made with the GPU otherwise idle, so their times are not inflated by other jobs.

  python tools/analyze_fast.py
Writes manuscript/computational_visual_media/fast_macros.tex.
"""
from __future__ import annotations

import os

import importlib.util
from math import comb
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("exp_bop", Path(__file__).resolve().parent / "export_bop_results.py")
eb = importlib.util.module_from_spec(spec)
spec.loader.exec_module(eb)
eb.BOP_ROOT = Path(os.environ.get("BOP_ROOT", "data/bop"))
MAN = ROOT / "manuscript" / "computational_visual_media"
KEY = {"lmo": "LMO", "lm": "LM", "tless": "TLESS"}


def load(root: Path, ds: str, fn: str) -> dict:
    eb.RES = root
    rows = [r for r in eb.read_jsonl(root / ds / fn) if "e_R_deg" in r]
    eb.add_sym_error(ds, rows)
    return {r["tag"]: r for r in rows}


def main() -> int:
    macros = ["% Auto-generated by tools/analyze_fast.py"]
    pool_f, pool_o, times_f, times_o, gain, loss = [], [], [], [], 0, 0
    for ds, name in eb.DATASETS:
        fast = load(ROOT / "bop6dof_results_fast", ds, "results_fast.jsonl")
        full = load(ROOT / "bop6dof_results", ds, "results.jsonl")
        tags = sorted(set(fast) & set(full))
        if not tags:
            continue
        f_ok = [fast[t]["e_R_sym_deg"] <= 10 for t in tags]
        o_ok = [full[t]["e_R_sym_deg"] <= 10 for t in tags]
        gain += sum(a and not b for a, b in zip(f_ok, o_ok))
        loss += sum(b and not a for a, b in zip(f_ok, o_ok))
        pool_f += f_ok
        pool_o += o_ok
        tf = [float(fast[t]["t_total_s"]) for t in tags]
        to = [float(full[t]["t_total_s"]) for t in tags]
        times_f += tf
        times_o += to
        etf = float(np.median([float(fast[t]["e_t_mm"]) for t in tags]))
        macros += [f"\\providecommand{{\\Fast{KEY[ds]}SR}}{{{100 * np.mean(f_ok):.0f}}}", f"\\providecommand{{\\Fast{KEY[ds]}N}}{{{len(tags)}}}",
                   f"\\providecommand{{\\Fast{KEY[ds]}Time}}{{{np.median(tf):.0f}}}", f"\\providecommand{{\\Fast{KEY[ds]}ET}}{{{etf:.0f}}}"]
        print(f"{name:7s} N={len(tags):3d}  1/8: SR10sym {100 * np.mean(f_ok):5.1f}%  median {np.median(tf):6.0f} s  e_t {etf:5.1f} mm | "
              f"full: SR10sym {100 * np.mean(o_ok):5.1f}%  median {np.median(to):6.0f} s")
    n = len(pool_f)
    nd = gain + loss
    p = 1.0 if nd == 0 else min(1.0, 2 * sum(comb(nd, i) for i in range(0, min(gain, loss) + 1)) / 2 ** nd)
    macros += [f"\\providecommand{{\\FastPoolN}}{{{n}}}", f"\\providecommand{{\\FastPoolSR}}{{{100 * np.mean(pool_f):.0f}}}",
               f"\\providecommand{{\\FastPoolFullSR}}{{{100 * np.mean(pool_o):.0f}}}", f"\\providecommand{{\\FastPoolTime}}{{{np.median(times_f):.0f}}}",
               f"\\providecommand{{\\FastPoolFullTime}}{{{np.median(times_o):.0f}}}", f"\\providecommand{{\\FastPoolGain}}{{{gain}}}",
               f"\\providecommand{{\\FastPoolLoss}}{{{loss}}}", f"\\providecommand{{\\FastPoolP}}{{{'<0.001' if p < 0.001 else f'={p:.2f}'}}}"]
    print(f"pooled  N={n}: 1/8 {100 * np.mean(pool_f):.1f}% at median {np.median(times_f):.0f} s | full {100 * np.mean(pool_o):.1f}% at "
          f"{np.median(times_o):.0f} s (shared GPU) | +{gain}/-{loss}, exact McNemar p={p:.2g}")
    (MAN / "fast_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print(f"[written] {MAN / 'fast_macros.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
