#!/usr/bin/env python3
"""
What limits the selection after all hypothesis sources (proposed search, four feed-forward initialisations, re-seeded
rotations about the principal axes), on both BOP samples (SR@10 sym.). Every frame the selection misses falls into one
of four classes, using the stages II-IV runs from the protocol's T0 bins as a probe of the correct basin:
  selection : one of the hypotheses is within 10 deg, but another one has a lower final loss;
  coverage  : no hypothesis is within 10 deg, but a run from a T0 bin is, with a lower loss than the selection
              (more hypotheses would fix the frame);
  loss      : a run from a T0 bin is within 10 deg, with a higher loss than the selection (the loss prefers the wrong pose);
  local     : no run reaches 10 deg, not even from the 15-30 deg bin (residual of the local stages).

  python tools/analyze_residual_failures.py
Writes manuscript/computational_visual_media/residual_macros.tex and benchmark_results/residual_failures.json.
"""
from __future__ import annotations

import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("ms", Path(__file__).resolve().parent / "analyze_multisource.py")
ms = importlib.util.module_from_spec(spec)
spec.loader.exec_module(ms)
KEY = {"lmo": "LMO", "lm": "LM", "tless": "TLESS"}


def main() -> int:
    counts = {}
    rows = []
    for root in (ROOT / "bop6dof_results", ROOT / "bop6dof_results_ext"):
        for ds in ("lmo", "lm", "tless"):
            if not (root / ds / "results.jsonl").exists():
                continue
            src = {k: ms.load(root, ds, fn) for k, fn in ms.SRC.items()}
            reseed = {k: ms.load(root, ds, fn, bins=True) for k, fn in ms.RESEED.items()}
            bins = ms.load(root, ds, "results_init_bins.jsonl", bins=True)
            for tag in src["ours"]:
                hyps = [src[k][tag] for k in src if tag in src[k]] + [r for k in reseed for r in reseed[k].get(tag, [])]
                sel = min(hyps, key=lambda r: float(r["loss"]))
                ok = float(sel["e_R_sym_deg"]) <= 10
                cls = "ok"
                if not ok:
                    good_b = [r for r in bins.get(tag, []) if float(r["e_R_sym_deg"]) <= 10]
                    if any(float(r["e_R_sym_deg"]) <= 10 for r in hyps):
                        cls = "selection"
                    elif good_b and min(float(r["loss"]) for r in good_b) < float(sel["loss"]):
                        cls = "coverage"
                    elif good_b:
                        cls = "loss"
                    else:
                        cls = "local"
                counts.setdefault(ds, {}).setdefault(cls, 0)
                counts[ds][cls] += 1
                rows.append({"root": root.name, "ds": ds, "tag": tag, "class": cls, "e_sel": float(sel["e_R_sym_deg"]),
                             "n_hyp": len(hyps)})
    tot = {}
    for ds, c in counts.items():
        for k, v in c.items():
            tot[k] = tot.get(k, 0) + v
    n = sum(tot.values())
    print(f"frames {n}: " + ", ".join(f"{k} {v}" for k, v in sorted(tot.items())))
    for ds, c in counts.items():
        print(f"  {ds:6s} " + ", ".join(f"{k} {v}" for k, v in sorted(c.items())))
    macros = ["% Auto-generated by tools/analyze_residual_failures.py", f"\\providecommand{{\\ResidN}}{{{n}}}",
              f"\\providecommand{{\\ResidFail}}{{{n - tot.get('ok', 0)}}}"]
    for k in ("ok", "selection", "coverage", "loss", "local"):
        macros.append(f"\\providecommand{{\\Resid{k.capitalize()}}}{{{tot.get(k, 0)}}}")
        for ds in counts:
            macros.append(f"\\providecommand{{\\Resid{KEY[ds]}{k.capitalize()}}}{{{counts[ds].get(k, 0)}}}")
    man = ROOT / "manuscript" / "computational_visual_media"
    (man / "residual_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    (ROOT / "benchmark_results" / "residual_failures.json").write_text(json.dumps({"counts": counts, "rows": rows}, indent=1), encoding="utf-8")
    print(f"[written] {man / 'residual_macros.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
