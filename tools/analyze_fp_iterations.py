#!/usr/bin/env python3
"""
FoundationPose's refiner from the same T0 with 5 iterations (released setting) and with 20 iterations, per rotation bin,
pooled over both BOP samples (SR@10 sym.). Its rotation update per iteration is an axis-angle vector bounded to +-20 deg
per component (tanh x rot_normalizer = 0.349 rad); if the failures beyond 60-90 deg were only a step-size limit, four
times the iterations would recover them.

  python tools/analyze_fp_iterations.py
Writes manuscript/computational_visual_media/fp_iter_macros.tex.
"""
from __future__ import annotations

import os

import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("exp_bop", Path(__file__).resolve().parent / "export_bop_results.py")
eb = importlib.util.module_from_spec(spec)
spec.loader.exec_module(eb)
eb.BOP_ROOT = Path(os.environ.get("BOP_ROOT", "data/bop"))
MAN = ROOT / "manuscript" / "computational_visual_media"
BINS = {"60-90": "C", "90-180": "D"}


def main() -> int:
    macros = ["% Auto-generated by tools/analyze_fp_iterations.py"]
    for b, letter in BINS.items():
        ok = {5: [], 20: []}
        for root in (ROOT / "bop6dof_results", ROOT / "bop6dof_results_ext"):
            eb.RES = root
            for ds, _ in eb.DATASETS:
                for it, fn in ((5, "baseline_foundationpose_refine.jsonl"), (20, "baseline_foundationpose_refine_it20.jsonl")):
                    recs = [r for r in eb.read_jsonl(root / ds / fn) if str(r.get("bin")) == b and "e_R_deg" in r]
                    eb.add_sym_error(ds, recs)
                    ok[it] += [float(r["e_R_sym_deg"]) <= 10 for r in recs]
        sr = {it: 100.0 * sum(v) / max(1, len(v)) for it, v in ok.items()}
        print(f"{b:7s} 5 it: {sr[5]:5.1f}% ({sum(ok[5])}/{len(ok[5])})   20 it: {sr[20]:5.1f}% ({sum(ok[20])}/{len(ok[20])})")
        macros += [f"\\providecommand{{\\FpItFiveBin{letter}}}{{{sr[5]:.0f}}}", f"\\providecommand{{\\FpItTwentyBin{letter}}}{{{sr[20]:.0f}}}",
                   f"\\providecommand{{\\FpItN}}{{{len(ok[20])}}}"]
    (MAN / "fp_iter_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    print(f"[written] {MAN / 'fp_iter_macros.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
