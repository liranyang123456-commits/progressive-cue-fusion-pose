#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Leak-test reports (leak_test_runs/leak_test_<ds>.json) -> manuscript/.../tables/tab_leak_test.tex (+ macros)."""
from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAN = ROOT / "manuscript" / "computational_visual_media"
NAME = {"ours_v10": "Proposed", "grid_adam": "Grid+Adam", "rand_restart_adam": "RandRestart+Adam", "adam_dr": "Adam-DR"}


def fmt(x) -> str:
    if x is None or x != x:
        return "--"
    if x == 0:
        return "0"
    return f"{x:.1e}" if x < 1e-2 else f"{x:.2f}"


def vdir(elev_deg: float, azim_deg: float):
    e, a = math.radians(elev_deg), math.radians(azim_deg)
    return (math.cos(e) * math.sin(a), math.sin(e), math.cos(e) * math.cos(a))


def view_err(rec: dict) -> float:
    """angle between the estimated and the labelled viewing direction (deg)"""
    u = vdir(float(rec["est_elev_deg"]), float(rec["est_azim_deg"]))
    v = vdir(float(rec["gt_elev_deg"]), float(rec["gt_azim_deg"]))
    c = max(-1.0, min(1.0, sum(x * y for x, y in zip(u, v))))
    return math.degrees(math.acos(c))


def main() -> int:
    rows, macros = [], ["% Auto-generated by tools/export_leak_table.py"]
    for ds in ("bunny", "dragon"):
        p = ROOT / "leak_test_runs" / f"leak_test_{ds}.json"
        if not p.exists():
            continue
        for res in json.loads(p.read_text(encoding="utf-8")):
            if res.get("status") != "ok":
                rows.append({"ds": ds, "m": res["method"], "mode": res["mode"], "status": res["status"]})
                continue
            tags = [t for t in res["per_tag"] if "A" in t]
            est = max((t["est_diff_max"] for t in tags), default=float("nan"))
            gt = min((t["gt_diff_max"] for t in tags), default=float("nan"))
            rep = [t["repeat_diff_max"] for t in tags if "repeat_diff_max" in t]
            ea = sum(view_err(t["A"]) for t in tags) / max(len(tags), 1)
            eb = sum(view_err(t["B"]) for t in tags) / max(len(tags), 1)
            verdict = res.get("verdict")
            if verdict is None:
                verdict = "identical" if est <= 1e-4 else ("differs" if res["mode"] == "strict" else "documented leak")
            rows.append({"ds": ds, "m": res["method"], "mode": res["mode"], "est": est, "gt": gt, "rep": (max(rep) if rep else None),
                         "nrep": int(res.get("n_repeats", 1 if rep else 0)), "ea": ea, "eb": eb, "verdict": verdict})
            key = f"Leak{ds.capitalize()}{''.join(w.capitalize() for w in res['method'].replace('v10', 'ten').split('_'))}{res['mode'].capitalize()}"
            macros += [f"\\newcommand{{\\{key}Est}}{{{fmt(est)}}}", f"\\newcommand{{\\{key}ErrA}}{{{ea:.2f}}}", f"\\newcommand{{\\{key}ErrB}}{{{eb:.2f}}}"]
            if rep:
                macros.append(f"\\newcommand{{\\{key}Rep}}{{{fmt(max(rep))}}}")
    if not rows:
        print("[leak] no reports yet")
        return 0
    L = ["\\begin{table}[t]", "\\centering", "\\footnotesize", "\\setlength{\\tabcolsep}{3pt}",
         "\\caption{Ground-truth leak test. Runs A and B share bit-identical observations (silhouette, depth, normals, RGB of three views) "
         "but receive different ground-truth labels (pose seeds 12291 vs.\\ 777); runs A$_2$, A$_3$, \\dots\\ repeat A with identical labels "
         "and measure run-to-run nondeterminism (number of repeats $k$ in brackets). \\emph{strict}: revised code; \\emph{legacy}: the two switches of the submitted code re-enabled "
         "(normal-map prior rotated by the ground-truth rotation; beam elevation band from the ground-truth elevation). "
         "$\\max|\\hat p_A-\\hat p_B|$: largest difference over views and over (dist, elev, azim) between the label-swapped runs; "
         "$\\max|\\hat p_A-\\hat p_{A_i}|$: same between A and its repeats; $\\min|p^{\\mathrm{gt}}_A-p^{\\mathrm{gt}}_B|$: smallest label "
         "difference; $\\bar e_{\\mathrm{dir}}$: mean viewing-direction error of the estimate with respect to its own labels, under label set A / B. "
         "Verdict: bitwise = identical estimates; within nondeterminism = label-swap difference no larger than twice the largest repeat difference; "
         "a legacy row whose estimates follow the labels documents the leak.}",
         "\\label{tab:leak_test}", "\\begin{tabular}{llllllcc}", "\\toprule",
         "Mesh & Method & Mode & $\\max|\\hat p_A-\\hat p_B|$ & $\\max|\\hat p_A-\\hat p_{A_i}|$ [$k$] & $\\min|p^{\\mathrm{gt}}_A-p^{\\mathrm{gt}}_B|$ & $\\bar e_{\\mathrm{dir}}$ A / B & verdict \\\\", "\\midrule"]
    for r in rows:
        if "est" not in r:
            L.append(f"{r['ds'].capitalize()} & {NAME.get(r['m'], r['m'])} & {r['mode']} & -- & -- & -- & -- & {r['status']} \\\\")
            continue
        rep_txt = f"{fmt(r['rep'])} [{r['nrep']}]" if r.get("rep") is not None else "--"
        L.append(f"{r['ds'].capitalize()} & {NAME.get(r['m'], r['m'])} & {r['mode']} & {fmt(r['est'])} & {rep_txt} & {r['gt']:.1f} & "
                 f"{r['ea']:.1f} / {r['eb']:.1f} & {r['verdict']} \\\\")
    L += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (MAN / "tables").mkdir(exist_ok=True)
    (MAN / "tables" / "tab_leak_test.tex").write_text("\n".join(L) + "\n", encoding="utf-8")
    (MAN / "leak_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    for r in rows:
        print({k: (round(v, 3) if isinstance(v, float) else v) for k, v in r.items()})
    print("[leak] table written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
