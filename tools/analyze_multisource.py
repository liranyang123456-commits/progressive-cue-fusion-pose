#!/usr/bin/env python3
"""
Real-data failure analysis and multi-source selection on the BOP frames (symmetry-aware, same footing as Table 4).

(1) Loss check: on frames where the initialisation-free estimate misses the 10-degree basin but stages II-IV from one
    of the protocol's T0 bins reach it, is the final geometric loss of that correct-basin pose lower than the loss of the
    estimate? (Both losses are the final value of the same stage-IV objective, polish_pose.)
(2) Selection by the geometric loss across hypothesis sources: the initialisation-free search and the four feed-forward
    geometry models, each refined by stages II-IV; per frame the pose with the lowest final loss is kept (no ground truth).

  python tools/analyze_multisource.py [--roots bop6dof_results,bop6dof_results_ext]
Writes manuscript/computational_visual_media/multisource_macros.tex and benchmark_results/multisource_summary.json.
"""
from __future__ import annotations

import os

import argparse
import importlib.util
import json
from math import comb
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("exp_bop", Path(__file__).resolve().parent / "export_bop_results.py")
eb = importlib.util.module_from_spec(spec)
spec.loader.exec_module(eb)
eb.BOP_ROOT = Path(os.environ.get("BOP_ROOT", "data/bop"))
MAN = ROOT / "manuscript" / "computational_visual_media"
KEY = {"lmo": "LMO", "lm": "LM", "tless": "TLESS"}
SRC = {"ours": "results.jsonl", "pi3": "results_init_pi3.jsonl", "vggt": "results_init_vggt.jsonl",
       "wid3r": "results_init_wid3r.jsonl", "cam3r": "results_init_cam3r.jsonl"}
FM_TIME = {"pi3": "baseline_pi3_init.jsonl", "vggt": "baseline_vggt_init.jsonl", "wid3r": "baseline_wid3r_init.jsonl",
           "cam3r": "baseline_cam3r_init.jsonl"}
RESEED = {"flip180": "results_init_flip180.jsonl", "flip90": "results_init_flip90.jsonl"}
COMBOS = {"Ours": ("ours",), "OursPi": ("ours", "pi3"), "OursFm": ("ours", "pi3", "vggt", "wid3r", "cam3r"),
          "OursFmFlip": ("ours", "pi3", "vggt", "wid3r", "cam3r", "flip180"),
          "OursFmReseed": ("ours", "pi3", "vggt", "wid3r", "cam3r", "flip180", "flip90"),
          "FmOnly": ("pi3", "vggt", "wid3r", "cam3r")}


def load_reseed(res: Path, ds: str, fn: str) -> dict:
    """Re-seeded hypotheses (several per frame): the lowest-loss one stands for the source, its time is the sum."""
    out = {}
    for tag, recs in load(res, ds, fn, bins=True).items():
        best = dict(min(recs, key=lambda r: float(r["loss"])))
        best["t_total_s"] = sum(float(r.get("t_total_s") or 0.0) for r in recs)
        out[tag] = best
    return out


def load(res: Path, ds: str, fn: str, bins: bool = False) -> dict:
    eb.RES = res
    rows = [r for r in eb.read_jsonl(res / ds / fn) if "e_R_deg" in r and "loss" in r]
    eb.add_sym_error(ds, rows)
    out = {}
    for r in rows:
        out.setdefault(r["tag"], []).append(r) if bins else out.__setitem__(r["tag"], r)
    return out


def times(res: Path, ds: str, fn: str) -> dict:
    return {r["tag"]: float(r.get("t_total_s") or 0.0) for r in eb.read_jsonl(res / ds / fn) if "tag" in r}


def mcnemar(b: int, c: int) -> float:
    n = b + c
    return 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, i) for i in range(0, min(b, c) + 1)) / 2 ** n)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--roots", default="bop6dof_results")
    args = ap.parse_args()
    roots = [ROOT / r.strip() for r in args.roots.split(",") if r.strip()]
    summary, macros = {"roots": [str(r) for r in roots]}, ["% Auto-generated by tools/analyze_multisource.py"]
    pool = {k: {"sel": [], "ora": [], "add": [], "t": []} for k in COMBOS}
    loss_all, rel_all, pairs = [], [], {k: [0, 0] for k in COMBOS}
    for ds, name in eb.DATASETS:
        per = {k: {"sel": [], "ora": [], "add": [], "t": []} for k in COMBOS}
        lc, rel = [], []
        for res in roots:
            if not (res / ds / "results.jsonl").exists():
                continue
            g = {k: load(res, ds, fn) for k, fn in SRC.items()}
            g.update({k: load_reseed(res, ds, fn) for k, fn in RESEED.items()})
            fm_t = {k: times(res, ds, fn) for k, fn in FM_TIME.items()}
            binsr = load(res, ds, "results_init_bins.jsonl", bins=True)
            for tag, ro in g["ours"].items():
                good = [r for r in binsr.get(tag, []) if r["e_R_sym_deg"] <= 10]
                if ro["e_R_sym_deg"] > 10 and good:
                    best = min(good, key=lambda r: r["loss"])
                    lc.append(best["loss"] < ro["loss"])
                    rel.append((best["loss"] - ro["loss"]) / ro["loss"])
                for k, combo in COMBOS.items():
                    c = [(s, g[s][tag]) for s in combo if tag in g[s]]
                    if not c:
                        continue
                    s_best, best = min(c, key=lambda x: x[1]["loss"])
                    per[k]["sel"].append(best["e_R_sym_deg"] <= 10)
                    per[k]["ora"].append(any(r["e_R_sym_deg"] <= 10 for _, r in c))
                    per[k]["add"].append(bool(best.get("add_lt_0.1d")))
                    per[k]["t"].append(sum(float(r.get("t_total_s") or 0.0) + (fm_t[s].get(tag, 0.0) if s in fm_t else 0.0) for s, r in c))
                    if k != "Ours":
                        a = ro["e_R_sym_deg"] <= 10
                        b = best["e_R_sym_deg"] <= 10
                        pairs[k][0] += int(b and not a)
                        pairs[k][1] += int(a and not b)
        key = KEY[ds]
        summary[name] = {"n": len(per["Ours"]["sel"]), "loss_check": {"n": len(lc), "lower": int(sum(lc)),
                         "rel_median": float(np.median(rel)) if rel else None}}
        macros += [f"\\providecommand{{\\Ms{key}N}}{{{len(per['Ours']['sel'])}}}",
                   f"\\providecommand{{\\Ms{key}LossN}}{{{len(lc)}}}", f"\\providecommand{{\\Ms{key}LossLower}}{{{int(sum(lc))}}}"]
        print(f"\n=== {name} (N={len(per['Ours']['sel'])}) loss check: correct basin lower in {sum(lc)}/{len(lc)}, "
              f"median relative difference {np.median(rel) if rel else float('nan'):+.2f}")
        for k in COMBOS:
            d = per[k]
            sr, ora = 100.0 * np.mean(d["sel"]), 100.0 * np.mean(d["ora"])
            summary[name][k] = {"sr10": sr, "oracle": ora, "add": 100.0 * np.mean(d["add"]), "t_med": float(np.median(d["t"]))}
            macros += [f"\\providecommand{{\\Ms{key}{k}SR}}{{{sr:.0f}}}", f"\\providecommand{{\\Ms{key}{k}Oracle}}{{{ora:.0f}}}",
                       f"\\providecommand{{\\Ms{key}{k}ADD}}{{{100.0 * np.mean(d['add']):.0f}}}"]
            print(f"  {k:7s} SR@10 sym {sr:5.1f}%  oracle {ora:5.1f}%  ADD(-S) {100.0 * np.mean(d['add']):5.1f}%  median time {np.median(d['t']):6.0f} s")
            for f in ("sel", "ora", "add", "t"):
                pool[k][f] += d[f]
        loss_all += lc
        rel_all += rel
    n = len(pool["Ours"]["sel"])
    summary["pooled"] = {"n": n, "loss_check": {"n": len(loss_all), "lower": int(sum(loss_all)), "rel_median": float(np.median(rel_all))}}
    macros += [f"\\providecommand{{\\MsPoolN}}{{{n}}}", f"\\providecommand{{\\MsLossN}}{{{len(loss_all)}}}",
               f"\\providecommand{{\\MsLossLower}}{{{int(sum(loss_all))}}}",
               f"\\providecommand{{\\MsLossRelMed}}{{{-100.0 * np.median(rel_all):.0f}}}"]
    print(f"\n=== pooled (N={n}) loss check: {sum(loss_all)}/{len(loss_all)} lower, median relative difference {np.median(rel_all):+.2f}")
    for k in COMBOS:
        d = pool[k]
        sr, ora = 100.0 * np.mean(d["sel"]), 100.0 * np.mean(d["ora"])
        nsel, nora = int(sum(d["sel"])), int(sum(d["ora"]))
        summary["pooled"][k] = {"sr10": sr, "oracle": ora, "n_sel": nsel, "n_oracle": nora, "add": 100.0 * np.mean(d["add"]),
                                "t_med": float(np.median(d["t"]))}
        macros += [f"\\providecommand{{\\MsPool{k}SR}}{{{sr:.0f}}}", f"\\providecommand{{\\MsPool{k}Oracle}}{{{ora:.0f}}}",
                   f"\\providecommand{{\\MsPool{k}NSel}}{{{nsel}}}", f"\\providecommand{{\\MsPool{k}NOracle}}{{{nora}}}",
                   f"\\providecommand{{\\MsPool{k}ADD}}{{{100.0 * np.mean(d['add']):.0f}}}",
                   f"\\providecommand{{\\MsPool{k}Time}}{{{np.median(d['t']):.0f}}}"]
        if k != "Ours":
            gain, loss = pairs[k]
            summary["pooled"][k].update({"gain": gain, "loss": loss, "p": mcnemar(gain, loss)})
            p = mcnemar(gain, loss)
            macros += [f"\\providecommand{{\\MsPool{k}Gain}}{{{gain}}}", f"\\providecommand{{\\MsPool{k}Loss}}{{{loss}}}",
                       f"\\providecommand{{\\MsPool{k}P}}{{{'<0.001' if p < 0.001 else f'={p:.2f}'}}}"]
        print(f"  {k:7s} SR@10 sym {sr:5.1f}% ({nsel}/{n})  oracle {ora:5.1f}% ({nora})  ADD(-S) {100.0 * np.mean(d['add']):5.1f}%  "
              f"median time {np.median(d['t']):6.0f} s" + (f"  vs ours: +{pairs[k][0]} / -{pairs[k][1]}" if k != "Ours" else ""))
    (MAN / "multisource_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    names = {"Ours": "Proposed (search, stages I--IV)", "OursPi": "\\quad + $\\pi^3$ hypothesis",
             "OursFm": "\\quad + $\\pi^3$, VGGT, Wid3R, CAM3R hypotheses", "FmOnly": "four feed-forward hypotheses, no search",
             "OursFmFlip": "\\quad\\quad + selection rotated $180^\\circ$ about each principal axis",
             "OursFmReseed": "\\quad\\quad + and $\\pm90^\\circ$ about each principal axis"}
    tl = ["% Auto-generated by tools/analyze_multisource.py", "\\begin{table}[!htbp]", "\\centering",
          "\\caption{Selection by the final geometric loss across hypothesis sources on the BOP frames of Table~\\ref{tab:bop_full}. Each "
          "feed-forward initialisation of Table~\\ref{tab:bop_fminit} is refined by stages II--IV; per frame the pose with the lowest "
          "final loss of the stage-IV objective is kept (no ground truth). SR@$10^\\circ$ sym.\\ in \\% per dataset and pooled, "
          "ADD(-S)$<0.1d$ recall and median seconds per frame summed over the sources, including the feed-forward inference. "
          "Re-seeded rows: the pose selected among the five is in addition rotated about the three principal axes of the mesh (vertex "
          "PCA), by $180^\\circ$ (three hypotheses) and then also by $\\pm90^\\circ$ (six more), each rotation refined by stages II--IV "
          "and entered in the same selection. "
          "Oracle: the best hypothesis chosen with the ground truth, an upper bound for the selection.}",
          "\\label{tab:multisource}", "\\footnotesize", "\\setlength{\\tabcolsep}{4pt}",
          "\\begin{tabular}{@{}lcccccc@{}}", "\\toprule",
          "Hypotheses & LM-O & LM & T-LESS & pooled & ADD(-S) & s/frame \\\\", "\\midrule"]
    for k in COMBOS:
        cells = [f"{summary[nm][k]['sr10']:.0f}" for _, nm in eb.DATASETS if nm in summary and k in summary[nm]]
        p_ = summary["pooled"][k]
        tl.append(f"{names[k]} & {' & '.join(cells)} & {p_['sr10']:.0f} & {p_['add']:.0f} & {p_['t_med']:.0f} \\\\")
    for k, lab in (("OursFm", "oracle of the five (ground truth)"), ("OursFmReseed", "oracle incl.\\ re-seeded (ground truth)")):
        cells = [f"{summary[nm][k]['oracle']:.0f}" for _, nm in eb.DATASETS if nm in summary and k in summary[nm]]
        if k in summary["pooled"]:
            tl.append(f"{lab} & {' & '.join(cells)} & {summary['pooled'][k]['oracle']:.0f} & -- & -- \\\\")
    tl += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]
    (MAN / "tables" / "tab_multisource.tex").write_text("\n".join(tl) + "\n", encoding="utf-8")
    (ROOT / "benchmark_results").mkdir(exist_ok=True)
    (ROOT / "benchmark_results" / "multisource_summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    print(f"\n[macros] {MAN / 'multisource_macros.tex'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
