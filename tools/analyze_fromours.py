#!/usr/bin/env python3
"""
The proposed method's initialisation-free estimate as the starting pose of other refiners (WAPR, SDFR, Diff-DOPE)
on the BOP frames, compared with the same refiners started from the protocol's T0 bins; and Diff-DOPE with its RGB
term enabled from the first iteration (LM-O / LM, whose models carry vertex colours).

Uses the symmetry handling, summary statistics and row format of tools/export_bop_results.py (release version), so
the numbers are on the same footing as Table 4 / Supplementary Table S7.

  python tools/analyze_fromours.py
Writes manuscript/computational_visual_media/fromours_macros.tex, tables/tab_bop_fromours_rows.tex (rows for S7)
and benchmark_results/bop_fromours_summary.json.
"""
from __future__ import annotations

import os

import importlib.util
import json
from math import comb
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("exp_bop", Path(__file__).resolve().parent / "export_bop_results.py")
eb = importlib.util.module_from_spec(spec)
spec.loader.exec_module(eb)
eb.RES = ROOT / "bop6dof_results"
eb.BOP_ROOT = Path(os.environ.get("BOP_ROOT", "data/bop"))
MAN = ROOT / "manuscript" / "computational_visual_media"
KEY = {"lmo": "LMO", "lm": "LM", "tless": "TLESS"}

GROUPS = {
    "ours": "results.jsonl",
    "ours_wapr": "baseline_wapr_from_ours.jsonl",
    "ours_sdfr": "baseline_sdfr_from_ours.jsonl",
    "ours_dd": "baseline_diffdope_from_ours.jsonl",
    "ours_fp": "baseline_foundationpose_from_ours.jsonl",
    "ours_mp": "baseline_megapose_from_ours.jsonl",
    "ours_gt": "baseline_gotrack_from_ours.jsonl",
    "msf_wapr": "baseline_wapr_from_msf.jsonl",
    "msf_gt": "baseline_gotrack_from_msf.jsonl",
    "wapr_refine": "baseline_wapr_refine.jsonl",
    "fp_refine": "baseline_foundationpose_refine.jsonl",
    "mp_refine": "baseline_megapose_refine.jsonl",
    "gt_refine": "baseline_gotrack_refine.jsonl",
    "sdfr": "baseline_sdfr.jsonl",
    "diffdope": "baseline_diffdope.jsonl",
    "diffdope_rgb": "baseline_diffdope_rgb.jsonl",
    "scflow2": "baseline_scflow2.jsonl",
}
COMBOS = (("ours_wapr", "OursWapr", "WAPR refine"), ("ours_fp", "OursFp", "FoundationPose refine"), ("ours_mp", "OursMp", "MegaPose refine"),
          ("ours_gt", "OursGt", "GoTrack"), ("ours_sdfr", "OursSdfr", "SDFR"), ("ours_dd", "OursDd", "Diff-DOPE"),
          ("msf_wapr", "MsfWapr", "WAPR refine, from the selection over all hypotheses"),
          ("msf_gt", "MsfGt", "GoTrack, from the selection over all hypotheses"))
REFINERS = (("wapr_refine", "WaprRef"), ("fp_refine", "Fp"), ("mp_refine", "Mp"), ("gt_refine", "Gt"), ("sdfr", "Sdfr"), ("diffdope", "Dd"),
            ("scflow2", "Scflow"))


def load(ds: str, fn: str) -> list[dict]:
    uniq = {}
    for r in eb.read_jsonl(eb.RES / ds / fn):
        if "e_R_deg" in r:
            uniq[(r.get("tag"), str(r.get("bin", "none")))] = r
    out = list(uniq.values())
    eb.add_sym_error(ds, out)
    return out


def mcnemar_exact(b: int, c: int) -> float:
    n = b + c
    if n == 0:
        return 1.0
    return min(1.0, 2 * sum(comb(n, i) for i in range(0, min(b, c) + 1)) / 2 ** n)


def ok(r: dict) -> bool:
    return float(r["e_R_sym_deg"]) <= 10


def main() -> int:
    macros = ["% Auto-generated by tools/analyze_fromours.py -- refiners started from the proposed method's estimate"]
    rows = ["% Auto-generated by tools/analyze_fromours.py -- rows for Supplementary Table S7"]
    summary, pool, pool_bin = {}, {k: [] for k, _, _ in COMBOS}, {k: [] for k, _ in REFINERS}
    pool_ours, pair_tot = [], {k: [0, 0] for k, _, _ in COMBOS}
    rgb_bins = {}
    tab = []
    for ds, name in eb.DATASETS:
        g = {k: load(ds, fn) for k, fn in GROUPS.items()}
        key = KEY[ds]
        by_ours = {r["tag"]: r for r in g["ours"]}
        pool_ours += [ok(r) for r in g["ours"]]
        print(f"\n=== {name} ===")
        rows.append(f"% {name}")
        tab += ["\\midrule", f"\\multicolumn{{11}}{{@{{}}l}}{{\\textit{{{name}}}}} \\\\",
                eb.row("\\textbf{Proposed (stages I--IV)}", "none", eb.summarize(g["ours"]))]
        for k, mk, label in COMBOS:
            s = eb.summarize(g[k])
            if not s:
                continue
            by = {r["tag"]: r for r in g[k]}
            tags = sorted(set(by_ours) & set(by))
            gain = sum((not ok(by_ours[t])) and ok(by[t]) for t in tags)
            loss = sum(ok(by_ours[t]) and (not ok(by[t])) for t in tags)
            pair_tot[k][0] += gain
            pair_tot[k][1] += loss
            pool[k] += [ok(by[t]) for t in tags]
            print(f"{label:12s} from ours: n={s['n']:3d} SR10sym={100*s['sr10_sym']:5.1f}% ADD={100*s['add01']:5.1f}% "
                  f"ARmssd={s['ar_mssd']:.2f} med e_t={s['et_median']:.1f} mm  gained={gain} lost={loss} p={mcnemar_exact(gain, loss):.3g}")
            macros += [f"\\providecommand{{\\Bop{key}{mk}SRtenSym}}{{{eb.pct(s['sr10_sym'])}}}",
                       f"\\providecommand{{\\Bop{key}{mk}ADD}}{{{eb.pct(s['add01'])}}}",
                       f"\\providecommand{{\\Bop{key}{mk}Gain}}{{{gain}}}", f"\\providecommand{{\\Bop{key}{mk}Loss}}{{{loss}}}"]
            rows.append(eb.row(f"Proposed $\\rightarrow$ {label}", "none", s))
            tab.append(eb.row(f"Proposed $\\rightarrow$ {label}", "none", s))
            summary.setdefault(ds, {})[k] = {kk: vv for kk, vv in s.items() if not isinstance(vv, tuple)}
        for k, mk in REFINERS:
            recs = [r for r in g[k] if str(r.get("bin")) == "90-180"]
            pool_bin[k] += [ok(r) for r in recs]
        recs_rgb = g["diffdope_rgb"]
        if recs_rgb:
            cells = []
            for b in eb.BINS:
                s_off = eb.summarize([r for r in g["diffdope"] if str(r.get("bin")) == b])
                s_on = eb.summarize([r for r in recs_rgb if str(r.get("bin")) == b])
                if not s_on:
                    continue
                bk = eb.BIN_KEY[b]
                by_off = {r["tag"]: r for r in g["diffdope"] if str(r.get("bin")) == b}
                by_on = {r["tag"]: r for r in recs_rgb if str(r.get("bin")) == b}
                tags = sorted(set(by_off) & set(by_on))
                gain = sum((not ok(by_off[t])) and ok(by_on[t]) for t in tags)
                loss = sum(ok(by_off[t]) and (not ok(by_on[t])) for t in tags)
                rgb_bins.setdefault(b, [0, 0, 0, 0, 0])
                rgb_bins[b][0] += sum(ok(by_off[t]) for t in tags)
                rgb_bins[b][1] += sum(ok(by_on[t]) for t in tags)
                rgb_bins[b][2] += len(tags)
                rgb_bins[b][3] += gain
                rgb_bins[b][4] += loss
                cells.append(f"{b}: {100*s_off['sr10_sym']:3.0f} -> {100*s_on['sr10_sym']:3.0f} (+{gain}/-{loss}, n={len(tags)})")
                macros += [f"\\providecommand{{\\Bop{key}DdRgb{bk}SRtenSym}}{{{eb.pct(s_on['sr10_sym'])}}}"]
                rows.append(eb.row("Diff-DOPE, RGB term on", b, s_on))
                tab += [eb.row("Diff-DOPE, mask + depth", b, s_off), eb.row("Diff-DOPE, mask + depth + RGB", b, s_on)]
            print("Diff-DOPE RGB off -> on (SR10sym):  " + " | ".join(cells))
    print("\n=== pooled over the BOP frames ===")
    n_ours = len(pool_ours)
    macros += [f"\\providecommand{{\\BopPoolN}}{{{n_ours}}}", f"\\providecommand{{\\BopPoolOursSRtenSym}}{{{eb.pct(np.mean(pool_ours))}}}",
               f"\\providecommand{{\\BopPoolOursOk}}{{{int(np.sum(pool_ours))}}}"]
    print(f"ours alone          n={n_ours} SR10sym={100*np.mean(pool_ours):5.1f}%  ({int(np.sum(pool_ours))} frames)")
    for k, mk, label in COMBOS:
        if pool[k]:
            g_, l_ = pair_tot[k]
            p = mcnemar_exact(g_, l_)
            print(f"ours -> {label:11s} n={len(pool[k])} SR10sym={100*np.mean(pool[k]):5.1f}%  gained={g_} lost={l_} p={p:.2g}")
            macros += [f"\\providecommand{{\\BopPool{mk}SRtenSym}}{{{eb.pct(np.mean(pool[k]))}}}",
                       f"\\providecommand{{\\BopPool{mk}Gain}}{{{g_}}}", f"\\providecommand{{\\BopPool{mk}Loss}}{{{l_}}}",
                       f"\\providecommand{{\\BopPool{mk}P}}{{{'<0.001' if p < 0.001 else f'={p:.2f}'}}}"]
    for k, mk in REFINERS:
        if pool_bin[k]:
            print(f"{k:12s} from T0, 90-180 bin: n={len(pool_bin[k])} SR10sym={100*np.mean(pool_bin[k]):5.1f}%")
            macros.append(f"\\providecommand{{\\BopPool{mk}BinDSRtenSym}}{{{eb.pct(np.mean(pool_bin[k]))}}}")
    bin_d = [np.mean(v) for v in pool_bin.values() if v]
    bin_d6 = [np.mean(pool_bin[k]) for k in ("wapr_refine", "fp_refine", "mp_refine", "gt_refine", "sdfr", "diffdope") if pool_bin[k]]
    from_o = [np.mean(pool[k]) for k, _, _ in COMBOS if pool[k] and not k.startswith("msf_")]
    if bin_d and from_o:
        macros += [f"\\providecommand{{\\BopPoolRefBinDMin}}{{{eb.pct(min(bin_d))}}}", f"\\providecommand{{\\BopPoolRefBinDMax}}{{{eb.pct(max(bin_d))}}}",
                   f"\\providecommand{{\\BopPoolSixBinDMin}}{{{eb.pct(min(bin_d6))}}}", f"\\providecommand{{\\BopPoolSixBinDMax}}{{{eb.pct(max(bin_d6))}}}",
                   f"\\providecommand{{\\BopPoolFromOursMin}}{{{eb.pct(min(from_o))}}}", f"\\providecommand{{\\BopPoolFromOursMax}}{{{eb.pct(max(from_o))}}}",
                   f"\\providecommand{{\\BopPoolNRef}}{{{len(bin_d)}}}", f"\\providecommand{{\\BopPoolNFromOurs}}{{{len(from_o)}}}"]
    if rgb_bins:
        print("Diff-DOPE RGB off -> on, pooled LM-O + LM:")
        tg = tl = tn = 0
        for b, (off, on, n, gain, loss) in rgb_bins.items():
            print(f"  {b:7s} n={n}  {100*off/n:5.1f}% -> {100*on/n:5.1f}%  (+{gain}/-{loss})")
            bk = eb.BIN_KEY[b]
            macros += [f"\\providecommand{{\\BopRgbPool{bk}Off}}{{{eb.pct(off / n)}}}", f"\\providecommand{{\\BopRgbPool{bk}On}}{{{eb.pct(on / n)}}}"]
            tg, tl, tn = tg + gain, tl + loss, tn + n
        p = mcnemar_exact(tg, tl)
        print(f"  all bins: {tn} paired runs, gained={tg} lost={tl} exact McNemar p={p:.3f}")
        macros += [f"\\providecommand{{\\BopRgbN}}{{{tn}}}", f"\\providecommand{{\\BopRgbGain}}{{{tg}}}", f"\\providecommand{{\\BopRgbLoss}}{{{tl}}}",
                   f"\\providecommand{{\\BopRgbP}}{{{p:.2f}}}"]
    (MAN / "tables").mkdir(parents=True, exist_ok=True)
    (MAN / "fromours_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    (MAN / "tables" / "tab_bop_fromours_rows.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")
    head = ["% Auto-generated by tools/analyze_fromours.py", "\\begin{table}[!htbp]", "\\centering",
            "\\caption{The proposed method as the starting pose of other refiners, and Diff-DOPE with its RGB term (same frames, metrics "
            "and symmetry handling as Table~\\ref{tab:bop_full}). \\emph{Proposed $\\rightarrow$ X}: refiner X started from the "
            "initialisation-free estimate of the proposed method (stages I--IV) instead of $T_0$; from the $90$--$180^\\circ$ bin the same "
            "refiners reach $\\BopPoolWaprRefBinDSRtenSym\\%$ (WAPR), $\\BopPoolFpBinDSRtenSym\\%$ (FoundationPose), "
            "$\\BopPoolMpBinDSRtenSym\\%$ (MegaPose, RGB-D), $\\BopPoolGtBinDSRtenSym\\%$ (GoTrack, RGB), "
            "$\\BopPoolSdfrBinDSRtenSym\\%$ (SDFR) and $\\BopPoolDdBinDSRtenSym\\%$ (Diff-DOPE) SR@$10^\\circ$ sym.\\ over the "
            "$\\BopPoolN$ frames (Table~\\ref{tab:bop_full}). \\emph{Diff-DOPE, mask + depth + RGB}: Diff-DOPE from the same $T_0$ bins "
            "with its masked RGB term (vertex colours of the BOP model) enabled from the first iteration in addition to the mask and "
            "depth terms of Table~\\ref{tab:bop_full}; LM-O and LM only, since the T-LESS CAD models carry no colour. Times: median "
            "seconds per frame of the refinement step (RTX~5090).}",
            "\\label{tab:bop_fromours}", "\\footnotesize", "\\setlength{\\tabcolsep}{3.5pt}", "\\begin{adjustbox}{max width=\\linewidth}",
            "\\begin{tabular}{@{}llccccccccc@{}}", "\\toprule",
            "Method & $T_0$ bin & $N$ & med.\\ $e_R$ & SR@10$^\\circ$ & med.\\ $e_R^{\\mathrm{sym}}$ & SR@10$^\\circ$ sym.\\ [CI] & "
            "ADD(-S)$<0.1d$ & AR$_{\\mathrm{MSSD}}$ & AR$_{\\mathrm{MSPD}}$ & s/frame \\\\"]
    tail = ["\\bottomrule", "\\end{tabular}", "\\end{adjustbox}", "\\end{table}"]
    (MAN / "tables" / "tab_bop_fromours.tex").write_text("\n".join(head + tab + tail) + "\n", encoding="utf-8")
    (ROOT / "benchmark_results" / "bop_fromours_summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    print(f"\n[written] {MAN / 'fromours_macros.tex'}, tables/tab_bop_fromours_rows.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
