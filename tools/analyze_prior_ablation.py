#!/usr/bin/env python3
"""
Summary of tools/run_prior_ablation.py: the 20 views on which WAPR's twelve-hypothesis estimator fails, solved by the
proposed method at the 1/8 budget with (ours_v10_fast_ref) and without (ours_v10_fast_sym) the upper-hemisphere seed
priors, next to the full-budget proposed method and WAPR.

  python tools/analyze_prior_ablation.py
Writes manuscript/computational_visual_media/prior_macros.tex and benchmark_results/prior_ablation_summary.json.
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from run_prior_ablation import VIEWS  # noqa: E402

MAN = ROOT / "manuscript" / "computational_visual_media"
ARMS = {"full": "ours_v10", "wapr": "wapr_full", "ref": "ours_v10_fast_ref", "sym": "ours_v10_fast_sym"}


def rows(run_dir: Path) -> dict[str, dict]:
    p = run_dir / "pose_metrics_summary.csv"
    if not p.exists():
        return {}
    with p.open(encoding="utf-8") as f:
        return {r["tag"]: r for r in csv.DictReader(f)}


def main() -> int:
    per_view, err = [], {k: [] for k in ARMS}
    for mesh, (n, tags) in VIEWS.items():
        runs = ROOT / "results" / "benchmark_runs" if (ROOT / "results" / "benchmark_runs").exists() else ROOT / "benchmark_runs"
        base = runs / f"{mesh}_{n}gt"
        data = {k: rows(base / d) for k, d in ARMS.items()}
        for t in tags:
            rec = {"mesh": mesh, "tag": t}
            for k in ARMS:
                r = data[k].get(t)
                rec[k] = float(r["rot_err_deg"]) if r else None
                rec[f"{k}_time"] = float(r["t_total_s"]) if r and r.get("t_total_s") else None
                if r:
                    err[k].append(float(r["rot_err_deg"]))
            if data["full"].get(t):
                rec["gt_elev"] = float(data["full"][t]["gt_elev_deg"])
            per_view.append(rec)
            print(f"{mesh:9s} {t}: " + "  ".join(f"{k}={rec[k]:7.2f}" if rec[k] is not None else f"{k}=   --  " for k in ARMS))
    summ = {}
    for k in ARMS:
        e = np.array(err[k])
        summ[k] = {"n": int(e.size), "solved": int(np.sum(e <= 10)), "median": float(np.median(e)) if e.size else None}
        print(f"{k:5s}: n={e.size:2d} solved={summ[k]['solved']:2d}  median e_R={summ[k]['median']}")
    both = [v for v in per_view if v["ref"] is not None and v["sym"] is not None]
    flips = sum((v["ref"] <= 10) != (v["sym"] <= 10) for v in both)
    print(f"paired views: {len(both)}, outcome changed by removing the priors: {flips}")
    macros = ["% Auto-generated by tools/analyze_prior_ablation.py -- hemisphere-agnostic seed ablation"]
    for k, name in (("full", "Full"), ("wapr", "Wapr"), ("ref", "Ref"), ("sym", "Sym")):
        macros += [f"\\providecommand{{\\Prior{name}N}}{{{summ[k]['n']}}}", f"\\providecommand{{\\Prior{name}Solved}}{{{summ[k]['solved']}}}"]
        if summ[k]["median"] is not None:
            macros.append(f"\\providecommand{{\\Prior{name}Med}}{{{summ[k]['median']:.2f}}}")
    macros.append(f"\\providecommand{{\\PriorChanged}}{{{flips}}}")
    MAN.mkdir(parents=True, exist_ok=True)
    (MAN / "prior_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    (ROOT / ("results/benchmark_results" if (ROOT / "results").exists() else "benchmark_results") / "prior_ablation_summary.json").write_text(json.dumps({"summary": summ, "views": per_view}, indent=1), encoding="utf-8")
    print("[written]", MAN / "prior_macros.tex")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
