#!/usr/bin/env python3
"""
Second, disjoint sample of BOP frames (seed 2027, same objects, frames per object and protocol as the first sample):
SR@10 sym. of every initialisation-free method and refiner on the second sample and pooled over both samples.

  python tools/analyze_replication.py
Merges the shard files of the second sample (results_shard*of*.jsonl -> results.jsonl, idempotent), then writes
manuscript/computational_visual_media/tables/tab_bop_second.tex, replication_macros.tex and
benchmark_results/bop_replication_summary.json. Times are not reported: the second sample ran on GPUs shared with
the other jobs of this revision.
"""
from __future__ import annotations

import os

import importlib.util
import json
from math import comb
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("exp_bop", Path(__file__).resolve().parent / "export_bop_results.py")
eb = importlib.util.module_from_spec(spec)
spec.loader.exec_module(eb)
eb.BOP_ROOT = Path(os.environ.get("BOP_ROOT", "data/bop"))
MAN = ROOT / "manuscript" / "computational_visual_media"
A, B = ROOT / "bop6dof_results", ROOT / "bop6dof_results_ext"
KEY = {"lmo": "LMO", "lm": "LM", "tless": "TLESS"}
INIT_FREE = (("ours_full", "Proposed", "Ours"), ("ours_ms", "\\quad + FM hypotheses", "OursMs"),
             ("ours_msf", "\\quad + FM and re-seeded hypotheses", "OursMsf"),
             ("msf_icp", "\\quad\\quad + depth ICP polish", "MsfIcp"),
             ("msf_fit", "\\quad\\quad + per-candidate ICP, fitness selection", "MsfFit"),
             ("wapr_full", "WAPR, 12 hypotheses", "WaprFull"), ("fp_full", "FoundationPose", "FpFull"), ("mp_full", "MegaPose", "MpFull"))
FIT_SEL = "results_msf_fit_sel.jsonl"  # tools/icp_fitness_select.py: the ICP on every hypothesis, the best depth fit kept
FROM_OURS = {"ours_wapr": ("WAPR refine", "OursWapr", "baseline_wapr_from_ours.jsonl"),
             "ours_fp": ("FoundationPose refine", "OursFp", "baseline_foundationpose_from_ours.jsonl"),
             "ours_mp": ("MegaPose refine", "OursMp", "baseline_megapose_from_ours.jsonl"),
             "ours_gt": ("GoTrack", "OursGt", "baseline_gotrack_from_ours.jsonl"),
             "ours_sdfr": ("SDFR", "OursSdfr", "baseline_sdfr_from_ours.jsonl"),
             "ours_dd": ("Diff-DOPE", "OursDd", "baseline_diffdope_from_ours.jsonl"),
             "msf_wapr": ("WAPR refine", "MsfWapr", "baseline_wapr_from_msf.jsonl"),
             "msf_gt": ("GoTrack", "MsfGt", "baseline_gotrack_from_msf.jsonl")}
REFINERS = (("wapr_refine", "WAPR refine", "WaprRef"), ("fp_refine", "FoundationPose refine", "FpRef"),
            ("mp_refine", "MegaPose refine", "MpRef"), ("gt_refine", "GoTrack", "GtRef"), ("scflow2", "SCFlow2", "Scflow"),
            ("diffdope", "Diff-DOPE", "Dd"), ("sdfr", "SDFR", "Sdfr"))


def merge_shards(root: Path) -> None:
    for ds, _ in eb.DATASETS:
        for stem in ("results", "results_fast"):
            shards = sorted((root / ds).glob(f"{stem}_shard*of*.jsonl"))
            if not shards:
                continue
            rows = {}
            for p in shards + ([root / ds / f"{stem}.jsonl"] if (root / ds / f"{stem}.jsonl").exists() else []):
                for r in eb.read_jsonl(p):
                    if "tag" in r:
                        rows[(r["tag"], str(r.get("bin", "none")))] = r
            (root / ds / f"{stem}.jsonl").write_text("".join(json.dumps(r) + "\n" for r in rows.values()), encoding="utf-8")


def load(root: Path, ds: str) -> dict:
    eb.RES = root
    g = eb.load_all(ds)
    for k, (_, _, fn) in FROM_OURS.items():
        recs = [r for r in eb.read_jsonl(root / ds / fn) if "e_R_deg" in r]
        eb.add_sym_error(ds, recs)
        g[k] = list({r["tag"]: r for r in recs}.values())
    recs = [r for r in eb.read_jsonl(root / ds / FIT_SEL) if "e_R_deg" in r]
    eb.add_sym_error(ds, recs)
    g["msf_fit"] = list({r["tag"]: r for r in recs}.values())
    return g


def ok(r: dict) -> bool:
    return float(r["e_R_sym_deg"]) <= 10


def sr(recs: list[dict]) -> str:
    return f"{100.0 * np.mean([ok(r) for r in recs]):.0f}" if recs else "--"


def mcnemar(b: int, c: int) -> float:
    n = b + c
    return 1.0 if n == 0 else min(1.0, 2 * sum(comb(n, i) for i in range(0, min(b, c) + 1)) / 2 ** n)


def main() -> int:
    merge_shards(B)
    data = {s: {ds: load(root, ds) for ds, _ in eb.DATASETS} for s, root in (("A", A), ("B", B))}
    macros = ["% Auto-generated by tools/analyze_replication.py"]
    summary = {}
    nB = sum(len(data["B"][ds]["ours_full"]) for ds, _ in eb.DATASETS)
    nA = sum(len(data["A"][ds]["ours_full"]) for ds, _ in eb.DATASETS)
    macros += [f"\\providecommand{{\\RepN}}{{{nB}}}", f"\\providecommand{{\\RepNall}}{{{nA + nB}}}"]

    def cells(key, filt=lambda r: True):
        out, allB, allAB = [], [], []
        for ds, _ in eb.DATASETS:
            rb = [r for r in data["B"][ds].get(key, []) if filt(r)]
            ra = [r for r in data["A"][ds].get(key, []) if filt(r)]
            out.append(sr(rb))
            allB += rb
            allAB += ra + rb
        return out, sr(allB), sr(allAB), allB, allAB

    lines = ["% Auto-generated by tools/analyze_replication.py", "\\begin{table}[!htbp]", "\\centering",
             "\\caption{Second, disjoint sample of BOP frames (same objects, frames per object and protocol as Table~\\ref{tab:bop_full}, "
             "frames drawn with another seed): SR@$10^\\circ$ sym.\\ in \\% per dataset and over the \\RepN{} frames of this sample, and "
             "pooled over both samples (\\RepNall{} frames). Times are not reported, since this sample ran on GPUs shared with the other "
             "jobs of the revision.}",
             "\\label{tab:bop_second}", "\\footnotesize", "\\setlength{\\tabcolsep}{4pt}", "\\begin{tabular}{@{}lccccc@{}}", "\\toprule",
             "Method & LM-O & LM & T-LESS & second sample & both samples \\\\", "\\midrule",
             "\\multicolumn{6}{@{}l}{\\textit{Initialisation-free (no $T_0$)}} \\\\"]
    for key, name, mk in INIT_FREE:
        c, b_, ab, recB, recAB = cells(key)
        lines.append(f"{name} & {' & '.join(c)} & {b_} & {ab} \\\\")
        macros += [f"\\providecommand{{\\Rep{mk}B}}{{{b_}}}", f"\\providecommand{{\\Rep{mk}AB}}{{{ab}}}"]
        for (ds, _), v in zip(eb.DATASETS, c):
            macros.append(f"\\providecommand{{\\Rep{KEY[ds]}{mk}B}}{{{v}}}")
        summary[key] = {"B": b_, "AB": ab, "per_ds_B": c}
    lines += ["\\midrule", "\\multicolumn{6}{@{}l}{\\textit{Refiners started from the proposed estimate}} \\\\"]
    for key, (name, mk, _) in FROM_OURS.items():
        c, b_, ab, _, _ = cells(key)
        start = "Proposed + FM + re-seeded" if key.startswith("msf_") else "Proposed"
        lines.append(f"{start} $\\rightarrow$ {name} & {' & '.join(c)} & {b_} & {ab} \\\\")
        macros += [f"\\providecommand{{\\Rep{mk}B}}{{{b_}}}", f"\\providecommand{{\\Rep{mk}AB}}{{{ab}}}"]
        summary[key] = {"B": b_, "AB": ab, "per_ds_B": c}
    for b, lab in (("15-30", "$15$--$30^\\circ$"), ("90-180", "$90$--$180^\\circ$")):
        lines += ["\\midrule", f"\\multicolumn{{6}}{{@{{}}l}}{{\\textit{{Refiners from $T_0$ in the {lab} bin}}}} \\\\"]
        for key, name, mk in REFINERS:
            c, b_, ab, _, _ = cells(key, lambda r, b=b: str(r.get("bin")) == b)
            lines.append(f"{name} & {' & '.join(c)} & {b_} & {ab} \\\\")
            bk = eb.BIN_KEY[b]
            macros += [f"\\providecommand{{\\Rep{mk}{bk}B}}{{{b_}}}", f"\\providecommand{{\\Rep{mk}{bk}AB}}{{{ab}}}"]
            summary[f"{key}@{b}"] = {"B": b_, "AB": ab, "per_ds_B": c}
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}"]

    # paired comparisons with the proposed estimate, pooled over both samples
    base = {}
    for s in ("A", "B"):
        for ds, _ in eb.DATASETS:
            for r in data[s][ds]["ours_full"]:
                base[(s, r["tag"])] = ok(r)
    for key, mk in (("ours_ms", "OursMs"), ("ours_wapr", "OursWapr"), ("ours_fp", "OursFp"), ("ours_sdfr", "OursSdfr"), ("ours_dd", "OursDd")):
        gain = loss = 0
        for s in ("A", "B"):
            for ds, _ in eb.DATASETS:
                for r in data[s][ds].get(key, []):
                    if (s, r["tag"]) in base:
                        gain += int(ok(r) and not base[(s, r["tag"])])
                        loss += int(base[(s, r["tag"])] and not ok(r))
        p = mcnemar(gain, loss)
        macros += [f"\\providecommand{{\\Rep{mk}Gain}}{{{gain}}}", f"\\providecommand{{\\Rep{mk}Loss}}{{{loss}}}",
                   f"\\providecommand{{\\Rep{mk}P}}{{{'<0.001' if p < 0.001 else f'={p:.2f}'}}}"]
        summary[key].update({"gain_AB": gain, "loss_AB": loss, "p_AB": p})
    (MAN / "tables" / "tab_bop_second.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (MAN / "replication_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")
    (ROOT / "benchmark_results" / "bop_replication_summary.json").write_text(json.dumps(summary, indent=1), encoding="utf-8")
    for k, v in summary.items():
        print(f"{k:22s} second sample {v['B']:>3s}%  both {v['AB']:>3s}%  per dataset (second) {v['per_ds_B']}"
              + (f"  vs ours: +{v['gain_AB']}/-{v['loss_AB']} p={v['p_AB']:.2g}" if "gain_AB" in v else ""))
    print(f"[written] tab_bop_second.tex, replication_macros.tex (second sample N={nB}, both N={nA + nB})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
